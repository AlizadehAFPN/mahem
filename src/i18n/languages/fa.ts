/**
 * The shape every language catalog must satisfy. Because `en` is typed as this,
 * TypeScript flags any key present in `fa` but missing (or misspelled) in `en`.
 */
export type TranslationResource = DeepString<typeof fa>;

// Turns the `as const` literal types (e.g. 'استخدامی') back into plain `string`
// so other catalogs may hold different values while keeping the same key shape.
type DeepString<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepString<T[K]>;
};
